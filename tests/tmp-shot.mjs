import { serve, launch } from './harness.mjs';
const { srv, url } = await serve();
const { browser, ctx } = await launch({ width: 960, height: 540 });
const p = await ctx.newPage();
const errs = [];
p.on('pageerror', e => errs.push('pageerror ' + e.message)); p.on('console', m => { if (m.type() === 'error' || m.type() === 'warning') errs.push(m.text()); });
const t0 = Date.now();
await p.goto(url + '/mumbai.html');
await p.waitForFunction(() => window.__game || document.querySelector('#loadErr:not(.hidden)'), null, { timeout: 120000 });
console.log('load s', (Date.now() - t0) / 1000, await p.textContent('#loadStage'));
await p.screenshot({ path: 'test-output/m-loader.png' });
await p.click('#btnFree');
await p.waitForTimeout(1500);
await p.screenshot({ path: 'test-output/m-intro.png' });
await p.evaluate(() => window.__game.rig.script && window.__game.rig.script.skip());
await p.waitForTimeout(1500);
await p.screenshot({ path: 'test-output/m-drive0.png' });
await p.keyboard.down('KeyW'); await p.waitForTimeout(4000); await p.keyboard.up('KeyW');
await p.screenshot({ path: 'test-output/m-drive1.png' });
console.log('speed', await p.evaluate(() => window.__game.sim.speed * 3.6), 'pos', await p.evaluate(() => window.__game.sim.pos.toArray().map(v => v.toFixed(1))));
console.log(errs.slice(0, 20).join('\n'));
await browser.close(); srv.close();
